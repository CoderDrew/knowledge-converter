"""Stop confidential documents, screenshots and text from being committed.

Usage (from the repository root):
    python scripts/check_confidential.py            # tracked and new (non-ignored) files
    python scripts/check_confidential.py --staged   # staged contents; used by .githooks/pre-commit
    python scripts/check_confidential.py PATH ...   # specific files

Rules:
1. Office documents, PDFs, mail files and similar may only be committed as
   backend/samples/sample-*.docx or sample-*.pptx, and must carry the marker
   that backend/scripts/generate_samples.py writes into their core properties.
2. Images may live in backend/samples/ (as sample-*), frontend/public/brand/
   or frontend/src/app/. Anywhere else (for example generated demo fixtures)
   an image must be byte-identical to one of the synthetic sample images.
3. No file, and no member of a ZIP-based file (Office packages, export ZIPs),
   may contain a blocked term. Built-in terms are stored as hashes so this
   file doesn't name them. Add your own terms (client names, project codes),
   one per line, to an untracked `.confidential-terms` file at the
   repository root.

Findings name the file and rule, never the matched text. Standard library only.
"""
from __future__ import annotations

import hashlib
import io
import re
import subprocess
import sys
import zipfile
from pathlib import Path, PurePosixPath

ROOT = Path(__file__).resolve().parents[1]
SAMPLE_MARKER = "Synthetic sample generated by backend/scripts/generate_samples.py"
SALT = "kc-guard:"
BLOCKED_HASHES = {
    "f4365c481c71788f76cd",  # client name
    "7ef4fe9becc2d25bd908",  # title of the client's source documents
}
DOCUMENT_EXTENSIONS = {
    ".doc", ".docx", ".docm", ".dot", ".dotx", ".dotm", ".ppt", ".pptx", ".pptm", ".pps", ".ppsx", ".pot", ".potx",
    ".xls", ".xlsx", ".xlsm", ".xlsb", ".csv", ".pdf", ".rtf", ".odt", ".odp", ".ods", ".msg", ".eml", ".one", ".vsdx",
}
IMAGE_EXTENSIONS = {".png", ".jpg", ".jpeg", ".gif", ".webp", ".bmp", ".tif", ".tiff", ".emf", ".wmf", ".heic", ".svg"}
SAMPLE_DOCUMENT = re.compile(r"^backend/samples/sample-[a-z0-9-]+\.(docx|pptx)$")
SAMPLE_IMAGE = re.compile(r"^backend/samples/sample-[a-z0-9-]+\.(png|jpe?g)$")
FREE_IMAGE_DIRS = ("frontend/public/brand/", "frontend/src/app/")
TEXT_MEMBERS = (".xml", ".rels", ".html", ".htm", ".json", ".txt", ".css", ".md", ".csv", ".svg", ".js")
MAX_MEMBER_BYTES = 50 * 1024 * 1024
WORD = re.compile(r"[a-z0-9]+")


def term_hash(term: str) -> str:
    return hashlib.sha256((SALT + term).encode()).hexdigest()[:20]


def normalise(text: str) -> str:
    return " ".join(WORD.findall(text.lower()))


def load_terms() -> tuple[set[str], int]:
    hashes = set(BLOCKED_HASHES)
    longest = 2
    local = ROOT / ".confidential-terms"
    if local.exists():
        for line in local.read_text(encoding="utf-8").splitlines():
            term = normalise(line)
            if term and not line.lstrip().startswith("#"):
                hashes.add(term_hash(term))
                longest = max(longest, len(term.split()))
    return hashes, longest


def contains_blocked(text: str, hashes: set[str], longest: int) -> bool:
    words = WORD.findall(text.lower())
    for n in range(1, longest + 1):
        for i in range(len(words) - n + 1):
            if term_hash(" ".join(words[i:i + n])) in hashes:
                return True
    return False


def git(*args: str) -> bytes:
    return subprocess.run(["git", *args], cwd=ROOT, check=True, capture_output=True).stdout


def candidate_files(staged: bool) -> list[tuple[str, bytes]]:
    if staged:
        names = git("diff", "--cached", "--name-only", "-z", "--diff-filter=ACMR").decode().split("\0")
        return [(name, git("show", f":{name}")) for name in names if name]
    names = git("ls-files", "-z", "--cached", "--others", "--exclude-standard").decode().split("\0")
    return [(name, (ROOT / name).read_bytes()) for name in names if name and (ROOT / name).is_file()]


def zip_texts(data: bytes) -> list[tuple[str, str]] | None:
    try:
        archive = zipfile.ZipFile(io.BytesIO(data))
    except zipfile.BadZipFile:
        return None
    texts = []
    for info in archive.infolist():
        if info.filename.lower().endswith(TEXT_MEMBERS) and info.file_size <= MAX_MEMBER_BYTES:
            texts.append((info.filename, archive.read(info).decode("utf-8", "ignore")))
    return texts


def sample_image_hashes() -> set[str]:
    hashes = set()
    samples = ROOT / "backend" / "samples"
    for path in samples.glob("sample-*"):
        data = path.read_bytes()
        if path.suffix.lower() in IMAGE_EXTENSIONS:
            hashes.add(hashlib.sha256(data).hexdigest())
        elif path.suffix.lower() in {".docx", ".pptx"}:
            with zipfile.ZipFile(path) as archive:
                for name in archive.namelist():
                    if "/media/" in name:
                        hashes.add(hashlib.sha256(archive.read(name)).hexdigest())
    return hashes


def check(name: str, data: bytes, terms: tuple[set[str], int], sample_images: set[str]) -> list[str]:
    problems = []
    suffix = PurePosixPath(name).suffix.lower()
    if suffix in DOCUMENT_EXTENSIONS:
        if not SAMPLE_DOCUMENT.match(name):
            problems.append("document files may only be committed as backend/samples/sample-*.docx|pptx")
        else:
            texts = dict(zip_texts(data) or [])
            if SAMPLE_MARKER not in texts.get("docProps/core.xml", ""):
                problems.append("sample is missing the generator marker; regenerate it with backend/scripts/generate_samples.py")
    if suffix in IMAGE_EXTENSIONS:
        free = SAMPLE_IMAGE.match(name) or name.startswith(FREE_IMAGE_DIRS)
        if not free and hashlib.sha256(data).hexdigest() not in sample_images:
            problems.append("image is not one of the synthetic sample images (allowed: backend/samples/sample-*, frontend/public/brand/, frontend/src/app/)")

    texts = zip_texts(data) if data[:4] == b"PK\x03\x04" else None
    if texts is not None:
        for member, text in texts:
            if contains_blocked(text, *terms):
                problems.append(f"blocked term inside archive member {member}")
    elif b"\0" not in data[:8192]:
        if contains_blocked(data.decode("utf-8", "ignore"), *terms):
            problems.append("blocked term in text")
    elif contains_blocked(data.decode("latin-1"), *terms):  # binary metadata (EXIF, PNG text chunks, OLE)
        problems.append("blocked term in binary content or metadata")
    return problems


def main(argv: list[str]) -> int:
    staged = "--staged" in argv
    paths = [arg for arg in argv if not arg.startswith("--")]
    if paths:
        files = [(Path(p).resolve().relative_to(ROOT).as_posix(), Path(p).read_bytes()) for p in paths]
    else:
        files = candidate_files(staged)
    terms, sample_images = load_terms(), sample_image_hashes()
    failures = 0
    for name, data in files:
        for problem in check(name, data, terms, sample_images):
            print(f"{name}: {problem}")
            failures += 1
    if failures:
        print(f"\n{failures} confidential-content problem(s). Replace real material with synthetic samples; see docs/SECURITY.md.")
        return 1
    print(f"Checked {len(files)} files: no confidential material found.")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
