"""Generate the synthetic sample documents in backend/samples/.

Usage (from backend/):
    python scripts/generate_samples.py

Everything is built from scratch here: no template, image, or text is read
from any other document. The content describes a fictional company
("Example Co.") and a generic expense-report process. Each file's core
properties carry SAMPLE_MARKER, which scripts/check_confidential.py
requires of every Office file committed to the repository.
"""
from __future__ import annotations

import datetime as dt
from pathlib import Path

from docx import Document
from docx.enum.style import WD_STYLE_TYPE
from docx.oxml import OxmlElement
from docx.oxml.ns import qn
from docx.shared import Inches
from PIL import Image, ImageDraw
from pptx import Presentation
from pptx.util import Inches as PptxInches

SAMPLE_MARKER = "Synthetic sample generated by backend/scripts/generate_samples.py"
SAMPLES = Path(__file__).resolve().parents[1] / "samples"
PNG = SAMPLES / "sample-screenshot.png"
DOCX = SAMPLES / "sample-expense-guide.docx"
PPTX = SAMPLES / "sample-expense-guide.pptx"
FIXED_DATE = dt.datetime(2026, 1, 1, tzinfo=dt.timezone.utc)


def mark(properties, title: str) -> None:
    properties.title = title
    properties.author = "Knowledge Converter samples"
    properties.last_modified_by = "Knowledge Converter samples"
    properties.comments = SAMPLE_MARKER
    properties.created = FIXED_DATE
    properties.modified = FIXED_DATE


def create_image() -> None:
    image = Image.new("RGB", (960, 540), "#f3f5f9")
    draw = ImageDraw.Draw(image)
    draw.rounded_rectangle((80, 70, 880, 470), radius=18, fill="white", outline="#4b5d78", width=4)
    draw.rectangle((80, 70, 880, 135), fill="#26364d")
    draw.text((115, 92), "EXAMPLE CO. EXPENSES (SYNTHETIC)", fill="white")
    draw.text((125, 180), "Report: Team offsite travel", fill="#26364d")
    draw.text((125, 220), "Cost centre: CC-1000", fill="#26364d")
    draw.text((125, 260), "Total: 245.00", fill="#26364d")
    draw.rounded_rectangle((125, 330, 350, 400), radius=10, fill="#3a6fd8")
    draw.text((200, 355), "SUBMIT", fill="white")
    image.save(PNG)


def add_hyperlink(paragraph, url: str, text: str) -> None:
    rid = paragraph.part.relate_to(url, "http://schemas.openxmlformats.org/officeDocument/2006/relationships/hyperlink", is_external=True)
    link = OxmlElement("w:hyperlink"); link.set(qn("r:id"), rid)
    run = OxmlElement("w:r"); t = OxmlElement("w:t"); t.text = text
    run.append(t); link.append(run); paragraph._p.append(link)


def create_docx() -> None:
    doc = Document()
    mark(doc.core_properties, "Submitting an Expense Report")
    doc.add_heading("Submitting an Expense Report", 1)
    intro = doc.add_paragraph("This synthetic job aid for the fictional Example Co. shows how a converter handles a typical how-to article. ")
    intro.add_run("All names and figures are invented.").bold = True
    doc.add_heading("Create the report", 2)
    doc.add_paragraph("Step 1: Open the Expenses workspace.", style="List Number")
    picture = doc.add_paragraph()
    picture.add_run().add_picture(str(PNG), width=Inches(6.2))
    doc.add_paragraph("Step 2: Choose cost centre CC-1000.", style="List Number")
    doc.add_paragraph("Attach a receipt for each line.", style="List Bullet")
    doc.add_paragraph("Add a short business purpose.", style="List Bullet")
    doc.add_paragraph("Step 3: Select Submit.", style="List Number")
    doc.add_heading("What to check", 2)
    table = doc.add_table(rows=4, cols=2)
    rows = [("Field", "Expected value"), ("Cost centre", "CC-1000"), ("Total", "245.00"), ("Status", "Submitted")]
    for row, (field, value) in zip(table.rows, rows):
        row.cells[0].text = field; row.cells[1].text = value
    tip = doc.styles.add_style("Quick Tip", WD_STYLE_TYPE.PARAGRAPH)
    doc.add_paragraph("Quick Tip: Save a draft if a receipt is missing.", style=tip)
    more = doc.add_paragraph("More examples: ")
    add_hyperlink(more, "https://example.com/expenses", "example.com/expenses")
    doc.save(DOCX)


def create_pptx() -> None:
    prs = Presentation()
    mark(prs.core_properties, "Submitting an Expense Report")
    title = prs.slides.add_slide(prs.slide_layouts[0])
    title.shapes.title.text = "Submitting an Expense Report"
    title.placeholders[1].text = "Example Co. training (synthetic sample)"

    steps = prs.slides.add_slide(prs.slide_layouts[1])
    steps.shapes.title.text = "Create the report"
    frame = steps.placeholders[1].text_frame
    frame.text = "Open the Expenses workspace"
    sub = frame.add_paragraph(); sub.text = "Choose cost centre CC-1000"; sub.level = 1
    nxt = frame.add_paragraph(); nxt.text = "Attach receipts and submit"
    steps.notes_slide.notes_text_frame.text = "Mention that drafts are saved automatically."

    shot = prs.slides.add_slide(prs.slide_layouts[5])
    shot.shapes.title.text = "The Expenses screen"
    shot.shapes.add_picture(str(PNG), PptxInches(1.5), PptxInches(1.6), width=PptxInches(7))

    check = prs.slides.add_slide(prs.slide_layouts[5])
    check.shapes.title.text = "What to check"
    tbl = check.shapes.add_table(3, 2, PptxInches(1), PptxInches(1.8), PptxInches(8), PptxInches(1.5)).table
    for r, (field, value) in enumerate([("Field", "Expected value"), ("Total", "245.00"), ("Status", "Submitted")]):
        tbl.cell(r, 0).text = field; tbl.cell(r, 1).text = value
    prs.save(PPTX)


if __name__ == "__main__":
    SAMPLES.mkdir(exist_ok=True)
    create_image(); create_docx(); create_pptx()
    print(f"Created {DOCX.name}, {PPTX.name}, and {PNG.name} in {SAMPLES}")
