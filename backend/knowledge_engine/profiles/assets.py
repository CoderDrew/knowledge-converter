ASSET_DIR = "assets/images/"


class HtmlAssetsProfile(OutputProfile):
    """A styled, portable page with images and CSS as separate files.

    `index.html` references `assets/styles.css` and `assets/images/…` with
    relative paths, so the extracted folder can be dropped onto any static
    host or into a CMS media library unchanged.
    """

    id = "assets"
    name = "HTML + Assets"
    summary = "A styled, portable page with extracted images and CSS in an organised assets folder."
    html_filename = "index.html"

    def _conventions(self, preview: bool) -> HtmlConventions:
        return HtmlConventions(
            image_src=data_uri if preview else (lambda asset: f"{ASSET_DIR}{asset.filename}"),
            callout=lambda kind, body: f'<aside class="kc-callout kc-callout-{kind}"><p>{body}</p></aside>',
            notice=lambda text: f'<span class="kc-notice">{html.escape(text)}</span>',
            unsupported_image=lambda asset: (
                f'<span class="kc-notice">[Image {html.escape(asset.filename)} is included in the package but browsers cannot display its format]</span>'
            ),
            section_class="kc-slide",
            notes_class="kc-notes",
            intrinsic_size=True,
            lazy_images=not preview,
        )

    def body(self, document: Document, *, preview: bool) -> str:
        return HtmlWriter(document, self._conventions(preview)).body()

    def _page(self, document: Document, *, preview: bool) -> str:
        head = f"<style>{STYLESHEET}</style>\n" if preview else '<link rel="stylesheet" href="assets/styles.css">\n'
        body = self.safe_body(document, preview=preview)
        return html_document(document.title, f'<article class="kc-document">\n{body}\n</article>', head=head, wrap=False)

    def build(self, document: Document) -> ProfileOutput:
        page = self._page(document, preview=False)
        files = {
            self.html_filename: page.encode("utf-8"),
            "assets/styles.css": STYLESHEET.encode("utf-8"),
            "manifest.json": generic_manifest(document, self.id, ASSET_DIR),
        }
        for asset in document.assets:
            files[f"{ASSET_DIR}{asset.filename}"] = asset.data
        return ProfileOutput(self.html_filename, page, files)

    def preview(self, document: Document) -> str:
        return self._page(document, preview=True)
