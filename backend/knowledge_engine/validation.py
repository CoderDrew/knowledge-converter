"""Structural validation of uploaded Office files.

Runs before python-docx/python-pptx see the file. It verifies that the bytes
are really an OOXML package of the claimed kind and that the archive is within
resource limits, so malformed, disguised, macro-enabled, encrypted, or
decompression-bomb uploads are rejected with a clear message. Nothing is ever
extracted to disk: parsers read members in memory and every output filename is
generated by the engine, never taken from the archive.
"""
from __future__ import annotations

import posixpath
import zipfile
from pathlib import Path, PurePosixPath

from lxml import etree

from knowledge_engine.errors import InvalidDocumentError, LimitExceededError, UnsupportedFileError
from knowledge_engine.limits import Limits


OLE_MAGIC = b"\xd0\xcf\x11\xe0\xa1\xb1\x1a\xe1"
ZIP_MAGIC = b"PK\x03\x04"
OFFICE_DOCUMENT_REL = "http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument"
STRICT_OFFICE_DOCUMENT_REL = "http://purl.oclc.org/ooxml/officeDocument/relationships/officeDocument"

MAIN_CONTENT_TYPES = {
    "docx": {"application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"},
    "pptx": {"application/vnd.openxmlformats-officedocument.presentationml.presentation.main+xml"},
}
MACRO_CONTENT_TYPES = {
    "application/vnd.ms-word.document.macroEnabled.main+xml",
    "application/vnd.ms-word.template.macroEnabledTemplate.main+xml",
    "application/vnd.ms-powerpoint.presentation.macroEnabled.main+xml",
    "application/vnd.ms-powerpoint.slideshow.macroEnabled.main+xml",
    "application/vnd.ms-powerpoint.template.macroEnabled.main+xml",
}
KIND_LABELS = {"docx": "Word document (.docx)", "pptx": "PowerPoint presentation (.pptx)"}

_SAFE_XML = etree.XMLParser(resolve_entities=False, no_network=True, huge_tree=False, load_dtd=False)


def kind_from_name(filename: str) -> str:
    suffix = Path(filename).suffix.lower().lstrip(".")
    if suffix in MAIN_CONTENT_TYPES:
        return suffix
    if suffix in {"doc", "ppt"}:
        raise UnsupportedFileError(
            "legacy_format",
            f"Legacy .{suffix} files are not supported. Open the file in Office and save it as .{suffix}x.",
        )
    if suffix in {"docm", "pptm", "dotm", "potm", "ppsm"}:
        raise UnsupportedFileError("macro_enabled", "Macro-enabled Office files are not accepted. Save a copy as .docx or .pptx.")
    raise UnsupportedFileError("unsupported_type", "Only Word (.docx) and PowerPoint (.pptx) files are supported.")


def _unsafe_member_name(name: str) -> bool:
    if not name or "\\" in name or "\x00" in name or name.startswith("/"):
        return True
    if len(name) > 2 and name[1] == ":":
        return True
    return ".." in PurePosixPath(name).parts


def _read_xml(archive: zipfile.ZipFile, name: str) -> etree._Element:
    try:
        return etree.fromstring(archive.read(name), _SAFE_XML)
    except KeyError:
        raise InvalidDocumentError("corrupted", "The file is damaged: a required Office package part is missing.") from None
    except (etree.XMLSyntaxError, zipfile.BadZipFile, ValueError, OSError):
        raise InvalidDocumentError("corrupted", "The file is damaged: an Office package part could not be read.") from None


def validate_package(path: Path, filename: str, limits: Limits) -> str:
    """Return "docx" or "pptx" for a structurally valid package, else raise."""
    kind = kind_from_name(filename)
    size = path.stat().st_size
    if size == 0:
        raise InvalidDocumentError("empty_file", "The file is empty.")
    if size > limits.max_upload_bytes:
        raise LimitExceededError("file_too_large", f"The file exceeds the {limits.max_upload_bytes // (1024 * 1024)} MB upload limit.")

    with path.open("rb") as handle:
        header = handle.read(8)
    if header.startswith(OLE_MAGIC):
        raise UnsupportedFileError(
            "encrypted_or_legacy",
            "This file is password-protected or uses a legacy Office format. Remove the password and save it as "
            f".{kind} before converting.",
        )
    if not header.startswith(ZIP_MAGIC):
        raise InvalidDocumentError("not_office_file", f"This is not a valid {KIND_LABELS[kind]}. The file contents do not match its extension.")

    try:
        archive = zipfile.ZipFile(path)
    except (zipfile.BadZipFile, OSError, ValueError):
        raise InvalidDocumentError("corrupted", "The file is damaged and could not be opened as an Office document.") from None

    with archive:
        infos = archive.infolist()
        if len(infos) > limits.max_archive_entries:
            raise LimitExceededError("archive_limits", "The document contains too many internal parts to process safely.")
        total = 0
        for info in infos:
            if _unsafe_member_name(info.filename):
                raise InvalidDocumentError("unsafe_archive", "The document package contains unsafe internal paths and was rejected.")
            if info.flag_bits & 0x1:
                raise UnsupportedFileError("encrypted_or_legacy", "The document package is encrypted and cannot be converted.")
            total += info.file_size
            if total > limits.max_uncompressed_bytes:
                raise LimitExceededError("archive_limits", "The document expands to more data than this service processes.")
            if info.file_size > 10 * 1024 * 1024 and info.compress_size and info.file_size / info.compress_size > limits.max_compression_ratio:
                raise LimitExceededError("archive_limits", "The document contains abnormally compressed data and was rejected.")
            if posixpath.basename(info.filename).lower() == "vbaproject.bin":
                raise UnsupportedFileError("macro_enabled", "The document contains macros. Save a macro-free copy before converting.")

        names = {info.filename for info in infos}
        if "[Content_Types].xml" not in names or "_rels/.rels" not in names:
            raise InvalidDocumentError("not_office_file", f"This is not a valid {KIND_LABELS[kind]}.")

        rels = _read_xml(archive, "_rels/.rels")
        main_part = None
        for rel in rels:
            if rel.get("Type") in {OFFICE_DOCUMENT_REL, STRICT_OFFICE_DOCUMENT_REL}:
                main_part = "/" + rel.get("Target", "").lstrip("/")
                break
        if not main_part:
            raise InvalidDocumentError("not_office_file", f"This is not a valid {KIND_LABELS[kind]}: it has no main document part.")
        if main_part.lstrip("/") not in names:
            raise InvalidDocumentError("corrupted", "The file is damaged: its main document part is missing.")

        content_types = _read_xml(archive, "[Content_Types].xml")
        main_type = None
        for node in content_types:
            if node.tag.endswith("Override") and node.get("PartName", "").lower() == main_part.lower():
                main_type = node.get("ContentType")
                break

    if main_type in MACRO_CONTENT_TYPES:
        raise UnsupportedFileError("macro_enabled", "Macro-enabled Office files are not accepted. Save a copy as .docx or .pptx.")
    if main_type not in MAIN_CONTENT_TYPES[kind]:
        other = next((k for k, types in MAIN_CONTENT_TYPES.items() if main_type in types), None)
        if other:
            raise InvalidDocumentError(
                "type_mismatch",
                f"The file is named .{kind} but contains a {KIND_LABELS[other]}. Rename it to .{other} and try again.",
            )
        raise UnsupportedFileError("unsupported_type", f"This Office file type is not supported. Save it as a standard .{kind} file.")
    return kind
